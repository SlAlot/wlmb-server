// 开发校验工具；不随插件常驻，不操作供网路由器。
'use strict'
const assert = require('node:assert/strict')
const fs=require('node:fs'),path=require('node:path'),{facts,bands}=require('./import-band-facts.cjs')
const { modelsFrom, differences, coverage } = require('./qmodem-audit.cjs')
const a = modelsFrom({ modem_support: { usb: { m1: { manufacturer: 'quectel', platform: 'qualcomm' } }, pcie: { m1: { manufacturer: 'quectel', platform: 'qualcomm' } }, device: { quectel: {} } } })
assert.equal(a.length, 2)
assert.throws(() => modelsFrom({ modem_support: { newbus: {} } }))
assert.throws(() => modelsFrom({ modem_support: { usb: { m1: { manufacturer: 'quectel' } } } }))
assert.throws(() => modelsFrom({ modem_support: { usb: { 'm_1': { manufacturer: 'q', platform: 'q' }, 'm-1': { manufacturer: 'q', platform: 'q' } } } }))
const before = { models: a, files: { LICENSE: 'abc', 'vendor/a.sh': 'old' } }
const after = { models: [{ ...a[0], platform: 'unisoc' }, { model: 'm2', transport: 'usb', vendor: 'huawei', platform: 'hisilicon' }], files: { LICENSE: 'def', 'vendor/a.sh': 'new' } }
const changes = differences(before, after)
for (const type of ['model-added', 'model-removed', 'model-protocol-changed', 'source-changed', 'license-changed']) assert.ok(changes.some(row => row.type === type))
const rows = coverage({ models: a }, { schema: 'WLMB-PROTOCOL-COVERAGE/1', models: [{ model: 'm1', family: 'quectel', platform: 'qualcomm', state: 'pending', parser: null, features: { radio: 'pending' }, hardwareAccepted: false }] })
assert.ok(rows.every(row => row.identified && row.mappingMatches && row.parser === null && !row.hardwareAccepted))
assert.ok(!coverage({ models: a }, { schema: 'WLMB-PROTOCOL-COVERAGE/1', models: [] })[0].identified)
assert.ok(!coverage({ models: a }, { schema: 'WLMB-PROTOCOL-COVERAGE/1', models: [{ model: 'm1', family: 'quectel', platform: 'unisoc' }] })[0].mappingMatches)
assert.throws(() => coverage({ models: a }, { schema: 'other', models: [] }))
console.log('Upstream drift audit: transport/schema/identity/platform/license/source-change checks passed; names never imply support.')
assert.deepEqual(bands('0'),[])
assert.deepEqual(bands('78/1/78'),[1,78])
assert.throws(()=>bands('1;reboot'))
assert.throws(()=>bands('0/78'))
const root=path.resolve(__dirname,'..'),inventory=JSON.parse(fs.readFileSync(path.join(root,'docs/model-bands.json'),'utf8')),reference=JSON.parse(fs.readFileSync(path.join(root,'docs/qmodem-upstream.json'),'utf8'))
assert.equal(inventory.revision,reference.revision)
assert.equal(inventory.sourceSha256,reference.files['application/qmodem/files/usr/share/qmodem/modem_support.json'])
assert.equal(inventory.profiles.length,reference.models.length)
for(const row of reference.models)assert.ok(inventory.profiles.some(r=>r.model===row.model&&r.transport===row.transport))
assert.deepEqual(facts({modem_support:{usb:{m:{lte_band:'1/3',sa_band:'78',nsa_band:'0'}}}})[0],{model:'m',transport:'usb',LTE:[1,3],NRSA:[78],NRNSA:[]})
